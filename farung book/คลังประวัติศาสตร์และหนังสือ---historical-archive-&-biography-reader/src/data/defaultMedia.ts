/**
 * Helper to auto-convert Google Sheets share or view links into live CSV export URLs
 */
export function normalizeSheetCsvUrl(rawUrl: string): string {
  if (!rawUrl) return '';
  const url = rawUrl.trim();

  // Handle Google Spreadsheets /d/{ID}/edit or similar
  const editMatch = url.match(/https:\/\/docs\.google\.com\/spreadsheets\/d\/([a-zA-Z0-9_-]+)/);
  if (editMatch && editMatch[1]) {
    if (url.includes('/pubhtml') || url.includes('/pub?')) {
      return url.replace(/\/pubhtml.*$/, '/pub?output=csv');
    }
    if (!url.includes('format=csv') && !url.includes('output=csv')) {
      return `https://docs.google.com/spreadsheets/d/${editMatch[1]}/export?format=csv`;
    }
  }

  return url;
}

export function extractYouTubeId(url: string): string | null {
  if (!url) return null;
  const match = url.match(/(?:youtu\.be\/|youtube\.com\/(?:embed\/|v\/|watch\?v=|watch\?.+&v=))([\w-]{11})/);
  return match ? match[1] : null;
}

export function extractYouTubeThumbnail(url: string): string | null {
  const id = extractYouTubeId(url);
  return id ? `https://img.youtube.com/vi/${id}/hqdefault.jpg` : null;
}

/**
 * Split a single CSV line respecting quotes and escaped quotes
 */
function splitCsvLine(line: string): string[] {
  const result: string[] = [];
  let cur = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const char = line[i];
    if (char === '"') {
      if (inQuotes && line[i + 1] === '"') {
        cur += '"';
        i++; // skip escaped quote
      } else {
        inQuotes = !inQuotes;
      }
    } else if (char === ',' && !inQuotes) {
      result.push(cur.trim());
      cur = '';
    } else {
      cur += char;
    }
  }
  result.push(cur.trim());
  return result;
}

/**
 * Robust CSV parser supporting Thai and English column headers, thumbnails, and descriptions
 * - รองรับไฟล์ HTML และวิดีโอ ที่ใส่ในคอลัมน์ปก หรือคอลัมน์ลิงก์ไฟล์
 * - ดึงรูปภาพปกอย่างถูกต้อง และไม่ส่งไฟล์ HTML ไปแสดงเป็นภาพ <img> เพื่อป้องกันรูปเสีย
 */
export function parseCSV(text: string, defaultCategory = 'ทั่วไป'): MediaItem[] {
  if (!text || !text.trim()) return [];

  // Normalize newline variations
  const normalized = text.replace(/\r\n/g, '\n').replace(/\r/g, '\n');
  const lines = normalized.split('\n').filter(l => l.trim().length > 0);
  if (lines.length < 2) return [];

  // Parse header line
  const headerCells = splitCsvLine(lines[0]);
  const rawHeaders = headerCells.map(h => h.replace(/^"|"$/g, '').trim().toLowerCase());
  
  // Find column indices
  // 1. Cover / Thumbnail: คอลัมน์ปก, ลิงก์ปก, รูปปก, ภาพปก, cover, thumbnail, image
  const idxThumb = rawHeaders.findIndex(h => 
    h.includes('คอลัมน์ปก') || h.includes('คอลัมลัมปก') || h.includes('ลิงก์ปก') || 
    h.includes('ลิงค์ปก') || h.includes('รูปปก') || h.includes('ภาพปก') || 
    h.includes('ปก') || h.includes('cover') || h.includes('thumb') || 
    h.includes('image') || h.includes('รูปภาพ') || h.includes('ภาพ')
  );

  // 2. Title: ชื่อไฟล์, ชื่อเรื่อง, ชื่อหนังสือ, ชื่อวิดีโอ, ชื่อ, title, name
  const idxTitle = rawHeaders.findIndex((h, idx) => {
    if (idx === idxThumb) return false;
    return (
      h.includes('ชื่อไฟล์') || h.includes('ชื่อเรื่อง') || h.includes('ชื่อหนังสือ') || 
      h.includes('ชื่อวิดีโอ') || h.includes('ชื่อ') || h.includes('title') || 
      h.includes('name') || h.includes('subject')
    );
  });

  // 3. URL / Raw File Link: ลิงก์ไฟล์ (raw url), raw url, url, link (must NOT be thumbnail or title)
  const idxUrl = rawHeaders.findIndex((h, idx) => {
    if (idx === idxThumb || idx === idxTitle) return false;
    if (h.includes('ปก') || h.includes('cover') || h.includes('thumb') || h.includes('ชื่อ') || h.includes('title') || h.includes('ลำดับ')) return false;
    return (
      h.includes('raw url') || h.includes('ลิงก์ไฟล์') || h.includes('ลิงค์ไฟล์') || h.includes('raw_url') ||
      h.includes('file') || h.includes('url') || h.includes('ลิงก์') || 
      h.includes('ลิงค์') || h.includes('link') || h.includes('drive') || h.includes('youtube')
    );
  });

  // 4. Category: หมวดหมู่, หมวด, category, ประเทศ, ทวีป, กลุ่ม, type
  const idxCategory = rawHeaders.findIndex((h, idx) => {
    if (idx === idxThumb || idx === idxUrl || idx === idxTitle) return false;
    return ['category', 'หมวดหมู่', 'หมวด', 'ประเทศ', 'ทวีป', 'ประเภท', 'กลุ่ม', 'type'].some(k => h.includes(k));
  });

  // 5. Description
  const idxDesc = rawHeaders.findIndex((h, idx) => {
    if (idx === idxThumb || idx === idxUrl || idx === idxTitle || idx === idxCategory) return false;
    return ['description', 'desc', 'คำอธิบาย', 'รายละเอียด', 'summary'].some(k => h.includes(k));
  });

  // Safe fallback indices if headers could not be found
  const titleCol = idxTitle !== -1 ? idxTitle : (rawHeaders.length > 1 ? 1 : 0);
  const urlCol = idxUrl !== -1 ? idxUrl : (rawHeaders.length > 3 ? 3 : (rawHeaders.length > 2 ? 2 : 1));

  const results: MediaItem[] = [];
  for (let i = 1; i < lines.length; i++) {
    const rawLine = lines[i];
    if (!rawLine.trim()) continue;

    const cells = splitCsvLine(rawLine);
    
    const valUrl = idxUrl !== -1 && cells[idxUrl] ? cells[idxUrl].replace(/^"|"$/g, '').trim() : '';
    const valThumb = idxThumb !== -1 && cells[idxThumb] ? cells[idxThumb].replace(/^"|"$/g, '').trim() : '';
    const fallbackUrl = (cells[urlCol] || '').replace(/^"|"$/g, '').trim();

    // Check if cell is an HTML URL or image URL
    const isValThumbHtml = valThumb.toLowerCase().includes('.html') || valThumb.toLowerCase().includes('.htm') || valThumb.includes('tontakan.github.io');
    const isValThumbImg = valThumb.toLowerCase().endsWith('.jpg') || valThumb.toLowerCase().endsWith('.jpeg') || valThumb.toLowerCase().endsWith('.png') || valThumb.toLowerCase().endsWith('.webp') || valThumb.includes('_image/') || valThumb.includes('/images/');
    
    const isValUrlImg = valUrl.toLowerCase().endsWith('.jpg') || valUrl.toLowerCase().endsWith('.jpeg') || valUrl.toLowerCase().endsWith('.png') || valUrl.toLowerCase().endsWith('.webp') || valUrl.includes('_image/');

    let finalUrl = '';
    let finalThumb: string | undefined = undefined;

    if (isValThumbHtml && (isValUrlImg || !valUrl)) {
      // User placed the HTML file URL in the cover column (คอลัมน์ปก)!
      finalUrl = valThumb;
      finalThumb = isValUrlImg ? valUrl : undefined;
    } else if (valUrl && !isValUrlImg) {
      finalUrl = valUrl;
      finalThumb = isValThumbImg ? valThumb : undefined;
    } else if (valThumb) {
      finalUrl = valThumb;
      finalThumb = isValUrlImg ? valUrl : undefined;
    } else if (fallbackUrl) {
      finalUrl = fallbackUrl;
    } else {
      // Search line for any URL
      const foundUrlCell = cells.find(c => c.startsWith('http://') || c.startsWith('https://') || c.includes('.html'));
      if (foundUrlCell) {
        finalUrl = foundUrlCell.replace(/^"|"$/g, '').trim();
      }
    }

    if (!finalUrl || (!finalUrl.startsWith('http://') && !finalUrl.startsWith('https://') && !finalUrl.includes('.'))) {
      continue;
    }

    // Never pass an HTML file as thumbnail image URL!
    if (finalThumb && (finalThumb.toLowerCase().includes('.html') || finalThumb.toLowerCase().includes('.htm'))) {
      finalThumb = undefined;
    }

    const isYoutube = finalUrl.includes('youtube.com') || finalUrl.includes('youtu.be');
    const isDrive = finalUrl.includes('drive.google.com') || finalUrl.includes('docs.google.com');
    const isPdf = finalUrl.toLowerCase().endsWith('.pdf') || finalUrl.toLowerCase().includes('.pdf');
    const sourceType: 'youtube' | 'drive' | 'pdf' | 'web' = isYoutube ? 'youtube' : (isDrive ? 'drive' : (isPdf ? 'pdf' : 'web'));

    const rawTitle = (cells[titleCol] || `รายการที่ ${i}`).replace(/^"|"$/g, '').trim();
    let title = rawTitle;
    let category = defaultCategory;

    // Check if category column is explicitly provided
    if (idxCategory !== -1 && cells[idxCategory]) {
      const c = cells[idxCategory].replace(/^"|"$/g, '').trim();
      if (c) category = c;
    } else if (cells[0] && isNaN(Number(cells[0].trim())) && !cells[0].trim().startsWith('http')) {
      category = cells[0].replace(/^"|"$/g, '').trim();
    } else {
      const bracketMatch = title.match(/^\[(.*?)\]\s*(.*)$/) || title.match(/^\((.*?)\)\s*(.*)$/);
      if (bracketMatch && bracketMatch[1] && bracketMatch[2]) {
        category = bracketMatch[1].trim();
        title = bracketMatch[2].trim();
      } else if (defaultCategory && defaultCategory !== 'ทั่วไป') {
        category = defaultCategory;
      } else if (isYoutube) {
        category = 'วิดีโอประวัติศาสตร์';
      } else {
        category = 'วรรณกรรมและหนังสือ';
      }
    }

    let rawDesc = idxDesc !== -1 && cells[idxDesc] ? cells[idxDesc].replace(/^"|"$/g, '').trim() : undefined;
    // Strip out any CSV / Google Sheets mentions from descriptions
    if (rawDesc) {
      rawDesc = rawDesc.replace(/โหลดสดจาก.*$/i, '').replace(/Google Sheet.*$/i, '').replace(/CSV.*$/i, '').replace(/Webview.*$/i, '').trim();
      if (!rawDesc) rawDesc = undefined;
    }

    let thumbnail = finalThumb;
    if (isYoutube) {
      const ytThumb = extractYouTubeThumbnail(finalUrl);
      thumbnail = ytThumb || finalThumb;
    }

    results.push({
      id: `media-csv-${i}-${encodeURIComponent(title.substring(0, 20)).replace(/%/g, '_')}`,
      category,
      title: title || `รายการที่ ${i}`,
      url: finalUrl,
      thumbnail,
      description: rawDesc,
      sourceType
    });
  }
  return results;
}
